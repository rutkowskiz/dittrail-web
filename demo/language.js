const LANGUAGE_KEY = "dittrail-language";
const LEGACY_LANGUAGE_KEY = "dittrail-demo-language";
const DOWNLOAD_COUNT_API = "https://api.github.com/repos/rutkowskiz/dittrail-web/releases/tags/v0.13-beta";
const DOWNLOAD_ASSET_NAMES = ["DitTrail-v0.13-windows-x64.exe", "DitTrail-v0.13-macos-arm64.dmg", "DitTrail-v0.13-macos-x64.dmg"];
let currentDownloadCount = null;

function getPolishDownloadLabel(count) {
    const mod10 = count % 10;
    const mod100 = count % 100;

    if (count === 1) {
        return translations.pl.downloadOne;
    }

    if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) {
        return translations.pl.downloadFew;
    }

    return translations.pl.downloadMany;
}

function getDownloadLabel(language, count) {
    if (language === "pl") {
        return getPolishDownloadLabel(count);
    }

    const dictionary = translations[language] || translations.en;
    return count === 1 ? dictionary.downloadOne : dictionary.downloadOther;
}

function updateDownloadCountText() {
    if (!Number.isInteger(currentDownloadCount) || currentDownloadCount < 0) {
        return;
    }

    const badge = document.getElementById("download-count");
    const value = document.getElementById("download-count-value");
    const label = document.getElementById("download-count-label");

    if (!badge || !value || !label) {
        return;
    }

    const language = translations[document.documentElement.lang]
        ? document.documentElement.lang
        : "en";

    value.textContent = String(currentDownloadCount);
    label.textContent = getDownloadLabel(language, currentDownloadCount);
    badge.hidden = false;
}

async function loadDownloadCount() {
    try {
        const response = await fetch(DOWNLOAD_COUNT_API, {
            headers: {
                Accept: "application/vnd.github+json"
            }
        });

        if (!response.ok) {
            return;
        }

        const release = await response.json();
        const assets = Array.isArray(release.assets) ? release.assets : [];
        const selected = DOWNLOAD_ASSET_NAMES.map(name => assets.find(item => item && item.name === name));
        if (selected.some(item => !item || !Number.isInteger(item.download_count) || item.download_count < 0)) {
            return;
        }

        currentDownloadCount = selected.reduce((sum, item) => sum + item.download_count, 0);
        updateDownloadCountText();
    } catch {
        // The counter is optional. Keep it hidden if GitHub cannot be reached.
    }
}

function applyLanguage(language) {
    const selected = translations[language] ? language : "en";
    const dictionary = translations[selected];

    document.documentElement.lang = selected;
    document.title = dictionary.pageTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute("content", dictionary.metaDescription);
    }

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (dictionary[key]) {
            element.textContent = dictionary[key];
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
        const key = element.dataset.i18nHtml;
        if (dictionary[key]) {
            element.innerHTML = dictionary[key];
        }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        const key = element.dataset.i18nAria;
        if (dictionary[key]) {
            element.setAttribute("aria-label", dictionary[key]);
        }
    });

    document.querySelectorAll(".language-button").forEach((button) => {
        const isActive = button.dataset.language === selected;
        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    localStorage.setItem(LANGUAGE_KEY, selected);
    updateDownloadCountText();
}

function getInitialLanguage() {
    const savedLanguage =
        localStorage.getItem(LANGUAGE_KEY) ||
        localStorage.getItem(LEGACY_LANGUAGE_KEY);

    if (translations[savedLanguage]) {
        return savedLanguage;
    }

    const browserLanguage = (navigator.language || "en")
        .toLowerCase()
        .split("-")[0];

    return translations[browserLanguage] ? browserLanguage : "en";
}

function initialiseLanguageSwitcher() {
    document.querySelectorAll(".language-button").forEach((button) => {
        button.addEventListener("click", () => applyLanguage(button.dataset.language));
    });

    applyLanguage(getInitialLanguage());
    loadDownloadCount();
}

document.addEventListener("DOMContentLoaded", initialiseLanguageSwitcher);
